    assert.strictEqual(new Set(values(/xml:id="([^"]+)"/g, twoIds)).size, 2, 'and are unique across copies');
    const seeded = await body(p('<text:bookmark text:name="m_2"/>') + p('{{ for a in xs }}<text:bookmark text:name="m"/>{{ endfor }}'), { xs: [1, 2] });
